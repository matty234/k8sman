package prom

import (
	"context"
	"encoding/json"
	"net/url"
	"sort"
	"strconv"
	"strings"
)

// Monitor identifies the operator object behind a scrape pool.
type Monitor struct {
	Kind      string `json:"kind"` // ServiceMonitor | PodMonitor | Probe | ScrapeConfig
	Namespace string `json:"namespace"`
	Name      string `json:"name"`
	// Endpoint is the index into spec.endpoints / podMetricsEndpoints.
	Endpoint int `json:"endpoint"`
}

// Target is one active scrape target.
type Target struct {
	ScrapePool         string            `json:"scrapePool"`
	ScrapeURL          string            `json:"scrapeUrl"`
	Health             string            `json:"health"` // up | down | unknown
	LastError          string            `json:"lastError,omitempty"`
	LastScrape         string            `json:"lastScrape,omitempty"`
	LastScrapeDuration float64           `json:"lastScrapeDuration,omitempty"`
	ScrapeInterval     string            `json:"scrapeInterval,omitempty"`
	Labels             map[string]string `json:"labels"`
	Target             *ObjectRef        `json:"target,omitempty"`
}

// TargetPool groups targets by scrape pool.
type TargetPool struct {
	ScrapePool string   `json:"scrapePool"`
	Monitor    *Monitor `json:"monitor,omitempty"`
	Up         int      `json:"up"`
	Down       int      `json:"down"`
	Unknown    int      `json:"unknown"`
	Targets    []Target `json:"targets"`
}

// TargetsResult is the GET /api/prom/targets payload.
type TargetsResult struct {
	Prometheus *Instance    `json:"prometheus"`
	Up         int          `json:"up"`
	Down       int          `json:"down"`
	Unknown    int          `json:"unknown"`
	Pools      []TargetPool `json:"pools"`
}

type promTarget struct {
	Labels             map[string]string `json:"labels"`
	ScrapePool         string            `json:"scrapePool"`
	ScrapeURL          string            `json:"scrapeUrl"`
	LastError          string            `json:"lastError"`
	LastScrape         string            `json:"lastScrape"`
	LastScrapeDuration float64           `json:"lastScrapeDuration"`
	Health             string            `json:"health"`
	ScrapeInterval     string            `json:"scrapeInterval"`
}

func fetchTargets(ctx context.Context, r requester, p *Instance) ([]promTarget, error) {
	data, _, err := promGet(ctx, r, p, "/api/v1/targets", url.Values{"state": {"active"}})
	if err != nil {
		return nil, err
	}
	var d struct {
		ActiveTargets []promTarget `json:"activeTargets"`
	}
	if err := json.Unmarshal(data, &d); err != nil {
		return nil, &UpstreamError{Status: 502, Message: "decode prometheus targets: " + err.Error()}
	}
	return d.ActiveTargets, nil
}

var poolKinds = map[string]string{
	"serviceMonitor": "ServiceMonitor",
	"podMonitor":     "PodMonitor",
	"probe":          "Probe",
	"scrapeConfig":   "ScrapeConfig",
}

// MonitorForPool parses the operator's scrape pool naming,
// `serviceMonitor/<namespace>/<name>/<endpoint>` (likewise podMonitor/,
// probe/, scrapeConfig/). Nil for pools not generated by the operator.
func MonitorForPool(pool string) *Monitor {
	parts := strings.Split(pool, "/")
	if len(parts) < 3 {
		return nil
	}
	kind, ok := poolKinds[parts[0]]
	if !ok {
		return nil
	}
	m := &Monitor{Kind: kind, Namespace: parts[1], Name: parts[2]}
	if len(parts) >= 4 {
		m.Endpoint, _ = strconv.Atoi(parts[3])
	}
	return m
}

// TargetFilter selects pools by monitor.
type TargetFilter struct {
	Kind, Namespace, Name string
}

// GroupTargets groups targets by scrape pool and maps pools to monitors.
func GroupTargets(raw []promTarget, f TargetFilter) TargetsResult {
	res := TargetsResult{Pools: []TargetPool{}}
	byPool := map[string]*TargetPool{}
	var order []string
	for _, t := range raw {
		m := MonitorForPool(t.ScrapePool)
		if f.Kind != "" || f.Namespace != "" || f.Name != "" {
			if m == nil || (f.Kind != "" && !strings.EqualFold(m.Kind, f.Kind)) || (f.Namespace != "" && m.Namespace != f.Namespace) || (f.Name != "" && m.Name != f.Name) {
				continue
			}
		}
		p := byPool[t.ScrapePool]
		if p == nil {
			p = &TargetPool{ScrapePool: t.ScrapePool, Monitor: m, Targets: []Target{}}
			byPool[t.ScrapePool] = p
			order = append(order, t.ScrapePool)
		}
		labels := nonNil(t.Labels)
		tg := Target{
			ScrapePool: t.ScrapePool, ScrapeURL: t.ScrapeURL, Health: t.Health, LastError: t.LastError,
			LastScrape: t.LastScrape, LastScrapeDuration: t.LastScrapeDuration, ScrapeInterval: t.ScrapeInterval,
			Labels: labels, Target: scrapeTargetRef(labels),
		}
		switch t.Health {
		case "up":
			p.Up++
			res.Up++
		case "down":
			p.Down++
			res.Down++
		default:
			p.Unknown++
			res.Unknown++
		}
		p.Targets = append(p.Targets, tg)
	}
	for _, k := range order {
		p := byPool[k]
		sort.SliceStable(p.Targets, func(i, j int) bool {
			x, y := p.Targets[i], p.Targets[j]
			if (x.Health == "down") != (y.Health == "down") {
				return x.Health == "down"
			}
			return x.ScrapeURL < y.ScrapeURL
		})
		res.Pools = append(res.Pools, *p)
	}
	sort.SliceStable(res.Pools, func(i, j int) bool {
		x, y := res.Pools[i], res.Pools[j]
		if (x.Down > 0) != (y.Down > 0) {
			return x.Down > 0
		}
		return x.ScrapePool < y.ScrapePool
	})
	return res
}

// scrapeTargetRef: the pod a target scrapes (operator relabelling sets
// namespace/pod/service on targets), else the service, else the node.
func scrapeTargetRef(l map[string]string) *ObjectRef {
	ns := l["namespace"]
	if ns != "" && l["pod"] != "" {
		return &ObjectRef{Kind: "Pod", Namespace: ns, Name: l["pod"]}
	}
	if ns != "" && l["service"] != "" {
		return &ObjectRef{Kind: "Service", Namespace: ns, Name: l["service"]}
	}
	if n := l["node"]; n != "" {
		return &ObjectRef{Kind: "Node", Name: n}
	}
	return nil
}
